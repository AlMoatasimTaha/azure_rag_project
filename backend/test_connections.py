import math
import os
from pathlib import Path
import sys

from azure.storage.blob import BlobServiceClient
from azure.cosmos import CosmosClient
from azure.ai.documentintelligence import DocumentIntelligenceClient
from azure.core.credentials import AzureKeyCredential
from azure.core.rest import HttpRequest
from azure.search.documents.indexes import SearchIndexClient
from dotenv import load_dotenv

if __package__:
    from .embedding_service import generate_embedding
else:
    from embedding_service import generate_embedding


load_dotenv(Path(__file__).with_name(".env"))

# Connection checks should fail promptly rather than retry for several minutes.
CLIENT_OPTIONS = {"connection_timeout": 10, "read_timeout": 20, "retry_total": 0}


class ConnectionCheckError(ValueError):
    """A safe diagnostic generated by this test, without service response data."""


def configuration(*names):
    values = [os.getenv(name, "").strip() for name in names]
    missing = [name for name, value in zip(names, values) if not value]
    if missing:
        raise ConnectionCheckError("Missing configuration: " + ", ".join(missing))
    return values


def report_failure(service, error, hint):
    print(f"{service}: FAIL")
    if isinstance(error, ConnectionCheckError):
        print(f"  Error: {error}")
    else:
        # Raw SDK exceptions can include credentials, URLs or response bodies.
        status = getattr(error, "status_code", None)
        if status is None:
            status = getattr(getattr(error, "response", None), "status_code", None)
        detail = f"HTTP {status}" if isinstance(status, int) else type(error).__name__
        print(f"  Error: {detail}. {hint}")
    return False


def test_blob_storage():
    try:
        connection_string, container_name = configuration(
            "AZURE_STORAGE_CONNECTION_STRING", "AZURE_STORAGE_CONTAINER"
        )

        blob_service_client = BlobServiceClient.from_connection_string(
            connection_string, **CLIENT_OPTIONS
        )

        container_client = blob_service_client.get_container_client(
            container_name
        )

        container_client.get_container_properties()

        print("Blob Storage: PASS")

        return True

    except Exception as error:
        return report_failure(
            "Blob Storage", error,
            "Check the storage connection string, configured container and network access."
        )


def test_cosmos_db():
    try:
        endpoint, key, database_name, container_name = configuration(
            "AZURE_COSMOS_ENDPOINT", "AZURE_COSMOS_KEY",
            "AZURE_COSMOS_DATABASE", "AZURE_COSMOS_CONTAINER"
        )

        client = CosmosClient(
            endpoint,
            credential=key,
            **CLIENT_OPTIONS,
        )

        database = client.get_database_client(database_name)
        container = database.get_container_client(container_name)

        container.read()

        print("Cosmos DB: PASS")

        return True

    except Exception as error:
        return report_failure(
            "Cosmos DB", error,
            "Check the Cosmos endpoint/key, database/container names and network access."
        )


def test_document_intelligence():
    try:
        endpoint, key = configuration(
            "AZURE_DOCUMENT_INTELLIGENCE_ENDPOINT", "AZURE_DOCUMENT_INTELLIGENCE_KEY"
        )

        client = DocumentIntelligenceClient(
            endpoint=endpoint,
            credential=AzureKeyCredential(key),
            **CLIENT_OPTIONS,
        )

        request = HttpRequest(
            "GET",
            f"{endpoint.rstrip('/')}/documentintelligence/info",
            params={"api-version": "2024-11-30"},
        )

        response = client.send_request(request)
        response.raise_for_status()

        print("Document Intelligence: PASS")

        return True

    except Exception as error:
        return report_failure(
            "Document Intelligence", error,
            "Check the Document Intelligence endpoint/key and network access."
        )


def test_foundry_embedding():
    try:
        configuration(
            "AZURE_OPENAI_ENDPOINT", "AZURE_OPENAI_API_KEY",
            "AZURE_OPENAI_EMBEDDING_DEPLOYMENT"
        )
        vector = generate_embedding("connection test")
        if (
            not isinstance(vector, list) or not vector
            or any(type(value) not in (int, float) for value in vector)
            or not all(math.isfinite(value) for value in vector)
        ):
            raise ConnectionCheckError("Expected a non-empty, finite numeric embedding vector.")

        print("Foundry Embedding: PASS")
        print(f"Embedding dimension: {len(vector)}")
        return True
    except Exception as error:
        return report_failure(
            "Foundry Embedding", error,
            "Check the OpenAI endpoint/key, embedding deployment, quota and network access."
        )


def test_azure_ai_search():
    try:
        endpoint, key, index_name = configuration(
            "AZURE_SEARCH_ENDPOINT", "AZURE_SEARCH_API_KEY", "AZURE_SEARCH_INDEX_NAME"
        )
        with SearchIndexClient(endpoint, AzureKeyCredential(key), **CLIENT_OPTIONS) as client:
            # Consume the SDK's paged result to actually contact the service.
            index_names = set(client.list_index_names())

        print("Azure AI Search service connection: PASS")
        state = "PASS" if index_name in index_names else "NOT CREATED YET"
        print(f"Configured index {index_name}: {state}")
        return True
    except Exception as error:
        return report_failure(
            "Azure AI Search service connection", error,
            "Check the Search endpoint, admin API key and network access; listing indexes requires admin access."
        )


def main():
    # Evaluate every check even when an earlier service fails.
    results = [
        test_blob_storage(),
        test_cosmos_db(),
        test_document_intelligence(),
        test_foundry_embedding(),
        test_azure_ai_search(),
    ]
    success = all(results)
    print(f"\nOverall: {'PASS' if success else 'FAIL'}")
    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
